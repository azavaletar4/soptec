  await click('Confirmar solicitud de devolución');
  await until('document.body.innerText.includes("Devolución en espera de recepción")');checks++;
  assert.equal(await evaluate('window.custody.units[0].status'),'pending_return');checks++;
  await click('Solicitar devolución');
  await evaluate(`{const quantity=document.querySelector('input[type=number]');quantity.value='3';quantity.dispatchEvent(new Event('input',{bubbles:true}));const note=document.querySelector('textarea');note.value='Sobrante';note.dispatchEvent(new Event('input',{bubbles:true}));}`);
  await click('Confirmar solicitud de devolución');
  await until('document.body.innerText.includes("Pendiente de recepción administrativa")');checks++;
  assert.equal(await evaluate('window.custody.materials[0].quantity'),10);checks++;
  assert.equal(await evaluate('calls.filter(c=>c.name==="request_material_return").length'),1);checks++;
